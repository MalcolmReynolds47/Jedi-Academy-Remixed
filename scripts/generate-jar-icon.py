#!/usr/bin/env python3
"""Render original JA:R emblem geometry locally. Requires Pillow; no network or model.
GPL-2.0-only. The design uses an original blade, split hilt and angular crest;
it contains no copied Jedi Knight logo, third-party image, font or model output.
"""
from pathlib import Path
from PIL import Image, ImageDraw
ROOT=Path(__file__).resolve().parents[1]
# Authored on a 256-square canvas. Shared geometry keeps SVG/ICO/SDL consistent.
SHAPES=[
 ("#080f1c",[(128,8),(225,52),(225,165),(188,210),(128,248),(68,210),(31,165),(31,52)]),
 ("#daae58",[(128,17),(216,57),(216,162),(181,204),(128,238),(75,204),(40,162),(40,57)]),
 ("#172536",[(128,27),(207,63),(207,158),(175,197),(128,227),(81,197),(49,158),(49,63)]),
 ("#294355",[(57,71),(88,85),(88,165),(128,200),(168,165),(168,85),(199,71),(199,154),(169,188),(128,217),(87,188),(57,154)]),
 ("#62ddf5",[(119,65),(128,38),(137,65),(137,156),(128,170),(119,156)]),
 ("#e6fcff",[(125,67),(128,52),(131,67),(131,153),(128,158),(125,153)]),
 ("#efc472",[(68,139),(108,139),(119,150),(119,160),(92,150),(68,150)]),
 ("#efc472",[(148,139),(188,139),(188,150),(164,150),(137,160),(137,150)]),
 ("#a6bdc6",[(119,168),(128,177),(137,168),(137,198),(128,207),(119,198)]),
 ("#efc472",[(120,210),(128,216),(136,210),(136,218),(128,224),(120,218)])]
def raster(size):
 image=Image.new("RGBA",(1024,1024));draw=ImageDraw.Draw(image)
 for color,points in SHAPES:draw.polygon([(x*4,y*4) for x,y in points],fill=color)
 return image.resize((size,size),Image.Resampling.LANCZOS)
def main():
 target=ROOT/"shared/icons";target.mkdir(parents=True,exist_ok=True)
 raster(256).save(target/"JAR.png")
 raster(256).save(target/"JAR.ico",sizes=[(n,n) for n in [16,20,24,32,40,48,64,128,256]])
 svg='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">\n<title>Jedi Academy Remixed original blade crest</title>\n'
 for color,points in SHAPES:svg+='<polygon fill="'+color+'" points="'+' '.join(str(x)+','+str(y) for x,y in points)+'"/>\n'
 (target/"JAR.svg").write_text(svg+'</svg>\n',encoding="utf8")
 raw=raster(64).tobytes();data=',\n'.join(','.join(str(v) for v in raw[i:i+32]) for i in range(0,len(raw),32))
 (ROOT/"shared/sdl/jar_icon.h").write_text('// Original JA:R icon; generated by scripts/generate-jar-icon.py. GPL-2.0-only.\nstatic const struct { unsigned width,height,bytes_per_pixel; unsigned char pixel_data[64*64*4]; } CLIENT_WINDOW_ICON={64,64,4,{\n'+data+'\n}};\n',encoding="utf8")
if __name__=="__main__":main()
